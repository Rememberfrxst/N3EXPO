/**
 * Writes artifacts/mobile/.env with the detected LAN IP for API access.
 * Run: node scripts/setup-mobile-env.mjs
 */
import os from 'os';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

function getLocalIp() {
  for (const ifaces of Object.values(os.networkInterfaces())) {
    for (const iface of ifaces ?? []) {
      if (iface.family === 'IPv4' && !iface.internal) {
        return iface.address;
      }
    }
  }
  return 'localhost';
}

const ip = getLocalIp();
const port = process.env.PORT ?? '3000';
const envPath = path.join(root, 'artifacts/mobile/.env');
const content = `# Auto-generated by scripts/setup-mobile-env.mjs
# Restart Expo after changes: npx expo start -c
EXPO_PUBLIC_API_URL=http://${ip}:${port}/api
`;

fs.writeFileSync(envPath, content, 'utf8');
console.log(`Wrote ${envPath}`);
console.log(`EXPO_PUBLIC_API_URL=http://${ip}:${port}/api`);
